function tf = isMissingValue(value)
%isMissingValue Whether a MATLAB value means "missing": [], <missing>, NaN or NaT
    tf = isempty(value) && ~ischar(value) && ~isstring(value) ...
        || (isstring(value) && isscalar(value) && ismissing(value)) ...
        || (isfloat(value) && isscalar(value) && isnan(value)) ...
        || (isdatetime(value) && isscalar(value) && isnat(value));
end
